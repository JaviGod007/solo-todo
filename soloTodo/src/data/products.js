export const createProduct = (newProduct) => {
  const current = getProducts();
  const created = { ...newProduct, id: Date.now() };
  current.push(created);
  localStorage.setItem('juegotodo_productos_v5', JSON.stringify(current));
  return created;
};

export const updateProduct = (id, updatedData) => {
  const updated = getProducts().map((p) => (p.id === Number(id) ? { ...p, ...updatedData } : p));
  localStorage.setItem('juegotodo_productos_v5', JSON.stringify(updated));
  return updated;
};

export const deleteProduct = (id) => {
  const filtered = getProducts().filter((p) => p.id !== Number(id));
  localStorage.setItem('juegotodo_productos_v5', JSON.stringify(filtered));
  return filtered;
};

